#!/usr/bin/env python3
"""Render docs/mcp-tools.md from docs/mcp-tools.json.

docs/mcp-tools.json is what `rvt-rs-mcp` reports for `tools/list` (names,
descriptions, input and output schemas, annotations). The end-to-end test
rvt-mcp/tests/mcp_stdio.rs fails when the committed file differs from what the
built server reports, and CI runs this script with --check, so the Markdown
cannot differ from the JSON either. Regenerate both after a change to a tool:

    RVT_UPDATE_MCP_TOOLS=1 cargo test -p rvt-rs-mcp --test mcp_stdio tool_contract
    python3 tools/ci/render-mcp-tools.py

Usage: render-mcp-tools.py [--check]
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs" / "mcp-tools.json"
TARGET = ROOT / "docs" / "mcp-tools.md"

ANNOTATIONS = (
    ("readOnlyHint", "read-only"),
    ("destructiveHint", "may overwrite"),
    ("idempotentHint", "idempotent"),
    ("openWorldHint", "open world"),
)


def ref_name(ref):
    return ref.rsplit("/", 1)[-1]


def type_of(schema):
    """A short name for the type a schema describes."""
    if schema is True or schema == {}:
        return "any"
    if schema is False:
        return "never"
    if "$ref" in schema:
        return "[%s](#%s)" % (ref_name(schema["$ref"]), ref_name(schema["$ref"]).lower())
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = []
            for part in schema[key]:
                name = type_of(part)
                if name not in parts:
                    parts.append(name)
            return " | ".join(parts)
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(kind_of(one, schema) for one in kind)
    if kind:
        return kind_of(kind, schema)
    return "any"


def kind_of(kind, schema):
    """A short name for one JSON type of a schema."""
    if kind == "array":
        items = schema.get("items")
        name = "array" if items is None else "array of " + type_of(items)
        if "minItems" in schema and schema.get("minItems") == schema.get("maxItems"):
            name += " (%d items)" % schema["minItems"]
        return name
    if kind == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return "object of " + type_of(extra) + " by name"
        return "object"
    return kind


def cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def properties_table(schema, with_required):
    properties = schema.get("properties") or {}
    if not properties:
        return ["No fields.", ""]
    required = set(schema.get("required") or [])
    header = "| Field | Type |" + (" Required |" if with_required else "") + " Description |"
    rule = "|---|---|" + ("---|" if with_required else "") + "---|"
    lines = [header, rule]
    for name, prop in properties.items():
        description = prop.get("description", "") if isinstance(prop, dict) else ""
        if isinstance(prop, dict) and "default" in prop:
            description = (description + " Default: %s." % json.dumps(prop["default"])).strip()
        row = "| `%s` | %s |" % (name, cell(type_of(prop)))
        if with_required:
            row += " %s |" % ("yes" if name in required else "no")
        row += " %s |" % cell(description)
        lines.append(row)
    lines.append("")
    return lines


def variants_table(schema):
    lines = ["| Value | Meaning |", "|---|---|"]
    for variant in schema.get("oneOf") or schema.get("anyOf") or []:
        if "const" in variant:
            value = json.dumps(variant["const"])
        elif "enum" in variant:
            value = " | ".join(json.dumps(v) for v in variant["enum"])
        else:
            value = type_of(variant)
        lines.append("| %s | %s |" % (value, cell(variant.get("description", ""))))
    lines.append("")
    return lines


def collect_definitions(tools):
    definitions = {}
    for tool in tools:
        for key in ("inputSchema", "outputSchema"):
            schema = tool.get(key) or {}
            for name, definition in (schema.get("$defs") or {}).items():
                if name in definitions and definitions[name] != definition:
                    sys.exit(
                        "error: type %s is defined differently by two tools (%s)" % (name, tool["name"])
                    )
                definitions[name] = definition
    return definitions


def render(tools):
    out = [
        "# MCP tools",
        "",
        "Generated by `tools/ci/render-mcp-tools.py` from [`mcp-tools.json`](mcp-tools.json), which is what",
        "`rvt-rs-mcp` reports for `tools/list`: the end-to-end test fails when the committed JSON",
        "differs from the built server's, and CI fails when this file differs from the JSON. Do not",
        "edit either by hand. [`mcp.md`](mcp.md) explains how the server works, the handle lifetime",
        "and what it does not read.",
        "",
        "Every tool takes `model` (a `model_id` from `open_model`, or a path), declares an",
        "`outputSchema`, and returns its answer as `structuredContent` and as the same JSON text. A",
        "failed call has `isError` set and a text message.",
        "",
        "| Tool | Summary |",
        "|---|---|",
    ]
    for tool in tools:
        summary = (tool.get("description") or "").split(". ")[0].rstrip(".") + "."
        out.append("| [`%s`](#%s) | %s |" % (tool["name"], tool["name"], cell(summary)))
    out.append("")
    for tool in tools:
        out.append("## %s" % tool["name"])
        out.append("")
        out.append(tool.get("description") or "")
        out.append("")
        annotations = tool.get("annotations") or {}
        flags = []
        for key, label in ANNOTATIONS:
            if key in annotations:
                flags.append("%s: %s" % (label, "yes" if annotations[key] else "no"))
        if flags:
            out.append("Hints: " + ", ".join(flags) + ".")
            out.append("")
        out.append("### Input")
        out.append("")
        out.extend(properties_table(tool.get("inputSchema") or {}, True))
        output = tool.get("outputSchema")
        out.append("### Output")
        out.append("")
        if output:
            out.extend(properties_table(output, True))
        else:
            out.append("No output schema.")
            out.append("")
    definitions = collect_definitions(tools)
    if definitions:
        out.append("## Types")
        out.append("")
        for name in sorted(definitions):
            definition = definitions[name]
            out.append("### %s" % name)
            out.append("")
            if definition.get("description"):
                out.append(" ".join(definition["description"].split()))
                out.append("")
            if "properties" in definition:
                out.extend(properties_table(definition, True))
            elif "oneOf" in definition or "anyOf" in definition:
                out.extend(variants_table(definition))
            else:
                out.append("Type: %s." % type_of(definition))
                out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    check = "--check" in sys.argv[1:]
    if not SOURCE.is_file():
        sys.exit("error: %s does not exist; generate it first (see this script's header)" % SOURCE)
    tools = json.loads(SOURCE.read_text(encoding="utf-8"))
    rendered = render(tools)
    if check:
        committed = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if committed.replace("\r\n", "\n") != rendered:
            sys.exit(
                "error: docs/mcp-tools.md differs from docs/mcp-tools.json; run "
                "`python3 tools/ci/render-mcp-tools.py` and commit it"
            )
        print("docs/mcp-tools.md matches docs/mcp-tools.json (%d tools)" % len(tools))
        return
    TARGET.write_text(rendered, encoding="utf-8")
    print("wrote %s (%d tools)" % (TARGET.relative_to(ROOT), len(tools)))


if __name__ == "__main__":
    main()
